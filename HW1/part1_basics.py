# 1.1 - Basic Arithmetic ---------

# a) Calculate how many minutes are in a week
# Store in minutes_per_week
minutes_per_week = 7 * 24 * 60

# b) Calculate how many seconds are in a day
# Store in seconds_per_day
seconds_per_day = 24 * 60 * 60

# c) Calculate 2 to the 10th power
# Store in power_result
power_result = 2 ** 10

print("Minutes per week:", minutes_per_week)
print("Seconds per day:", seconds_per_day)
print("2 to the 10th power:", power_result)

